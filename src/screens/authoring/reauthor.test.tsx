/** Every authoring test in this repo seeds a blank, valid game and drives everything else through
 *  the UI from there — `playerCount` has no editor screen (it is set at game-creation time, outside
 *  this phase's scope), so it is the one field seeded rather than clicked. */
async function seed(playerCount: number): Promise<void> {
  for (const game of await getAllGames()) await deleteGame(game.id);
  useDefinitionStore.getState().setDefinition(createEmptyDefinition('blank', 'blank', '2026-01-01T00:00:00.000Z'));
  localStorage.clear();
  await putGame({
    ...createEmptyDefinition(GAME_ID, 'Reauthored', '2026-01-01T00:00:00.000Z'),
    playerCount,
  });
}

function openGame(path = `/game/${GAME_ID}/pools`) {
  const router = createMemoryRouter(routes, { initialEntries: [path] });
  const utils = render(<RouterProvider router={router} />);
  return { router, user: userEvent.setup(), ...utils };
}

type Router = ReturnType<typeof openGame>['router'];
type User = ReturnType<typeof openGame>['user'];

async function goto(router: Router, path: string) {
  await act(async () => {
    await router.navigate(path);
  });
}

/** Adds a rule, which navigates straight to its editor (RuleSetsScreen's own behaviour) — returns
 *  its id, then leaves the router parked on the new rule's route. Caller navigates back to add more. */
async function addRule(router: Router, user: User): Promise<string> {
  await goto(router, `/game/${GAME_ID}/rules`);
  await screen.findByRole('button', { name: 'Add rule' });
  await user.click(screen.getByRole('button', { name: 'Add rule' }));
  await waitFor(() => expect(router.state.location.pathname).toMatch(/\/rules\/.+$/));
  return definition().ruleSets.at(-1)!.id;
}

async function addTemplate(router: Router, user: User): Promise<string> {
  await goto(router, `/game/${GAME_ID}/cards`);
  await screen.findByRole('button', { name: 'Add card' });
  await user.click(screen.getByRole('button', { name: 'Add card' }));
  await waitFor(() => expect(router.state.location.pathname).toMatch(/\/cards\/.+$/));
  return definition().templates.at(-1)!.id;
}

/** Points a "Left side"/"Right side"/"Amount" ValueRefPicker chip at `cardIndex(<cardKind>, indexId)`. */
async function setCardIndexRef(
  user: User,
  chip: HTMLElement,
  cardRadioName: string | RegExp,
  indexId: string
) {
  await user.click(chip);
  await user.click(screen.getByRole('radio', { name: 'A card index' }));
  await user.click(screen.getByRole('button', { name: 'Card' }));
  await user.click(screen.getByRole('radio', { name: cardRadioName }));
  await user.selectOptions(screen.getByRole('combobox', { name: 'Index' }), indexId);
}

/**
 * Every condition-shaped field authored through the UI (`rule.condition`, `activation.costCheck`,
 * `matching.where`) comes out wrapped in a one-child AND group — `CriteriaGroupEditor`'s "+
 * condition" always operates on a `CriteriaGroup`, never produces a bare `GameCriteria` at the top.
 * mtgish.ts/vtesish.ts, hand-written TypeScript object literals with no such constraint, use a BARE
 * criteria directly for several of these fields (`lethalCondition`, the `oustRule` condition,
 * `equipmentAbilityRule.activation.costCheck`). This is snag (3) from the task brief, generalised:
 * every occurrence below is asserted against the group-wrapped shape the UI actually produces, which
 * is semantically identical (an AND of one child is that child) but not byte-identical to the
 * fixture's own literal — the difference is asserted deliberately, not normalised away.
 */
const oneCriteria = (node: object) => ({ kind: 'group' as const, combinator: 'and' as const, children: [node] });

/**
 * `ChipPopover` only closes on Escape or a pointerdown OUTSIDE its own wrapper (`ChipPopover.tsx`) —
 * it never closes itself just because its value was set. Two chips sharing a generic field label
 * ("Zone", "Card", "Index", "Of") both left open at once makes `getByRole` ambiguous, so every
 * distinct chip's configuration below that is followed by opening ANOTHER, non-nested chip closes
 * this one first. The "Kind" heading is present and inert on every rule editor screen, so it is a
 * safe universal click-outside target.
 */
async function closePopovers(user: User) {
  await user.click(screen.getByRole('heading', { name: 'Kind' }));
}


/**
 * Step 47 — GATE, phase 4. §8's own words: "Re-author a trimmed `mtgish` and `vtesish` **through the
 * UI**, export, and diff against the TypeScript fixtures."
 *
 * This file renders the real authoring screens (via the real route table, the real store, the real
 * IndexedDB-backed layout — exactly `rules.test.tsx`/`cards.test.tsx`'s idiom) and drives them with
 * `userEvent`, the way a designer would: clicks, selects, typed text. Nothing here calls a store
 * action directly except the one-time seed of an empty game (the same seed every authoring test in
 * this repo already performs before it starts clicking).
 *
 * TRIMMED, deliberately (§8 step 47's own instruction): this does not rebuild either fixture card for
 * card. It covers every DISTINCT v2 construct the two fixtures actually use — determined by grepping
 * `mtgish.ts`/`vtesish.ts` for `kind:` literals, not by guessing — and no more. A construct proven
 * once (in either fixture) is not re-proven in the other; the report names which fixture proves which
 * construct. The v2-new inventory, and where each is proven:
 *
 *   RuleSet modes    continuous, modifier, replacement, activation   — both fixtures use all four
 *   Effect kinds     announceAction, counterAction, attach,           — mtgish
 *                    setController, eliminateSeat
 *                    sealedChoice                                     — vtesish
 *   TargetSelector   matching, hostOf                                 — mtgish (matching also vtesish)
 *   CardRef          host, candidate                                  — mtgish
 *   SeatRef          owner                                            — mtgish
 *                    relative, sum (quantifier)                       — vtesish
 *   ActionSelector   action{ref:topOfStack}                           — mtgish
 *   PriorityWindow   non-default fields (start, includeStart)         — vtesish
 *
 * `attachedTo` (TargetSelector), `controller` (SeatRef), `replacedTarget` (CardRef), and
 * `cardTag`/`activeSeatCount`/`replacedAmount`/`actionField` (ValueRef) are v2-new but used by
 * NEITHER fixture (confirmed by the same grep) — already proven authorable by
 * `selectorChips.test.tsx`/`refChips.test.tsx`/`effectRow.test.tsx`, not re-proven here.
 *
 * Diff strategy (§8's own instruction: construct by construct, not one opaque blob): ids are
 * autogenerated by the store (`p1`, `z1`, `rs1`, …) and cannot match the fixtures' hand-picked
 * constants, so a byte-for-byte `toEqual` against `mtgish`/`vtesish` is impossible by construction —
 * and would prove nothing about the UI even if it were. Instead, every semantic field (kind unions,
 * operators, literals, offsets, mode flags) is asserted against the fixture's own literal value, and
 * every id-shaped field is asserted to resolve to the right AUTHORED entity by construction (the
 * variable holding the id IS the entity), which is the strongest claim byte-identity could add.
 *
 * Comments below say "AC-adjacent: <id>" rather than "AC: <id>" deliberately: `traceability.test.ts`
 * scans every `.test.tsx?` file for the literal string "AC:" and treats it as a proof-file for that
 * criterion. This file corroborates several MTG/V criteria (the same outcome, on a re-authored and
 * round-tripped definition) but is not their traceability record — the engine/component tests §9.1
 * names already are, and duplicating the tag here would make the traceability table claim two
 * "kinds" of proof (headless behavioural vs. UI-authored-then-replayed) as one undifferentiated list.
 */

